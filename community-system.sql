grant execute on function public.community_delete_comment(bigint) to authenticated;

create or replace function public.community_ban_user(p_user_id uuid,p_reason text)
returns boolean language plpgsql security definer set search_path=''
as $$
declare reason text:=trim(coalesce(p_reason,''));
begin
  if (select auth.uid()) is null then raise exception 'Требуется авторизация.'; end if;
  if reason='' then raise exception 'Укажите причину блокировки.'; end if;
  if char_length(reason)>500 then raise exception 'Причина блокировки слишком длинная.'; end if;
  if not (select public.community_can_manage_user(p_user_id)) then raise exception 'Этого пользователя нельзя заблокировать с вашей ролью.'; end if;
  update public.profiles set is_banned=true,ban_reason=reason,banned_at=now(),banned_by=(select auth.uid()) where id=p_user_id;
  return true;
end $$;
revoke all on function public.community_ban_user(uuid,text) from public;
grant execute on function public.community_ban_user(uuid,text) to authenticated;

