create or replace function public.community_profile_guard()
returns trigger language plpgsql security definer set search_path=''
as $$
declare me uuid:=(select auth.uid()); me_role text;
begin
  if me is null then raise exception 'Требуется авторизация.'; end if;
  select role into me_role from public.profiles where id=me;
  if old.role='owner' and old.id<>me then raise exception 'Профиль владельца защищён.'; end if;
  if new.role<>old.role then raise exception 'Роль изменяется только штатным механизмом владельца.'; end if;
  if (new.is_banned is distinct from old.is_banned or new.ban_reason is distinct from old.ban_reason or new.banned_at is distinct from old.banned_at or new.banned_by is distinct from old.banned_by)
     and not (select public.community_can_manage_user(old.id)) then
    raise exception 'Недостаточно прав для модерации этого пользователя.';
  end if;
  if me<>old.id and (new.nickname is distinct from old.nickname or new.avatar_url is distinct from old.avatar_url or new.bio is distinct from old.bio or new.created_at is distinct from old.created_at) then
    if me_role<>'owner' then raise exception 'Нельзя редактировать чужой профиль.'; end if;
  end if;
  return new;
end $$;
drop trigger if exists community_profile_guard on public.profiles;
create trigger community_profile_guard before update on public.profiles for each row execute function public.community_profile_guard();

create or replace function public.community_delete_comment(p_comment_id bigint)
returns boolean language plpgsql security definer set search_path=''
as $$
declare author_id uuid; me uuid:=(select auth.uid());
begin
  if me is null then raise exception 'Требуется авторизация.'; end if;
  select c.author_id into author_id from public.comments c where c.id=p_comment_id;
  if author_id is null then return false; end if;
  if author_id<>me and not (select public.community_can_manage_user(author_id)) then raise exception 'Недостаточно прав для удаления этого комментария.'; end if;
  delete from public.comments where id=p_comment_id;
  return true;
end $$;
